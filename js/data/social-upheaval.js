/**
 * Year-aligned social upheavals 1920–2025.
 * Rows raise crisis coefficients and unlock life-intervention threads
 * (conscription, unemployment, devaluation, flight). Matching prefers
 * active MORTALITY_HISTORY ids so butterfly suppress still works.
 */

function u(row) {
  return Object.freeze({
    id: row.id,
    label: row.label,
    years: row.years.slice(),
    regions: row.regions ? row.regions.slice() : null,
    countriesAny: row.countriesAny ? row.countriesAny.slice() : null,
    historyIds: row.historyIds ? row.historyIds.slice() : null,
    narrativeIds: row.narrativeIds ? row.narrativeIds.slice() : null,
    threads: Object.freeze((row.threads || []).slice()),
    heat: row.heat ?? 2,
    trust: row.trust ?? -1,
    worldPressure: row.worldPressure ?? 6,
    crisisBoost: row.crisisBoost ?? 12,
    score: row.score ?? 14,
  });
}

