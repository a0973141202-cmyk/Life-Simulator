export function namesFromKey(key) {
  if (key && NAME_PACKS[key]) return NAME_PACKS[key];
  return null;
}

export function nameKeyForCountry(country = "") {
  const text = String(country || "");
  if (!text) return null;
  for (const [needle, key] of COUNTRY_NAME_KEYS) {
    if (text.includes(needle)) return key;
  }
  return null;
}

export function namePackForCountry(country = "") {
  return namesFromKey(nameKeyForCountry(country));
}

export function packFromEthnicity(ethnicity) {
  if (ethnicity?.names?.surnames?.length) return ethnicity.names;
  if (ethnicity?.namesKey) return namesFromKey(ethnicity.namesKey);
  return null;
}
