/**
 * Familial health markers. Tags are contextual, not moral:
 * a carrier state can be strain in one climate and protection in another.
 *
 * risk_*     = carrier / polygenic susceptibility (often silent)
 * condition_* = expressed phenotype
 */

function c({
  id,
  label,
  description,
  observation,
  inheritMode,
  hooks = ["health"],
  advantageIn = [],
  strainIn = ["health"],
  ancestryHooks = [],
  expressedLabel = null,
  expressedChance = 0.08,
  carrierChance = 0.42,
  xLinked = false,
  statMods = {},
  expressedStatMods = {},
}) {
  return {
    id,
    tag: `risk_${id}`,
    expressedTag: expressedLabel ? `condition_${id}` : null,
    expressedLabel,
    label,
    description,
    observation,
    inheritMode,
    hooks,
    advantageIn,
    strainIn,
    ancestryHooks,
    expressedChance,
    carrierChance,
    xLinked,
    statMods,
    expressedStatMods,
    valence: "contextual",
  };
}

