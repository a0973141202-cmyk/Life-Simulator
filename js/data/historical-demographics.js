export function interpolateSeries(series, year) {
  if (!series) return 0;
  const keys = Object.keys(series).map(Number).sort((a, b) => a - b);
  if (!keys.length) return 0;
  const y = Number(year);
  if (!Number.isFinite(y) || y <= keys[0]) return series[keys[0]];
  if (y >= keys[keys.length - 1]) return series[keys[keys.length - 1]];
  for (let i = 0; i < keys.length - 1; i += 1) {
    const a = keys[i];
    const b = keys[i + 1];
    if (y >= a && y <= b) {
      const t = (y - a) / (b - a);
      return series[a] + (series[b] - series[a]) * t;
    }
  }
  return series[keys[keys.length - 1]];
}

export function regionPopulationMillions(region, year) {
  return interpolateSeries(REGION_POP_MILLIONS[region], year);
}

export function worldUrbanShare(year) {
  return interpolateSeries(WORLD_URBAN_SHARE, year);
}

export function kindPopulationMult(kind, year) {
  const series = KIND_POP_MULT[kind] || KIND_POP_MULT.city;
  return interpolateSeries(series, year);
}

export function isRuralKind(kind) {
  return RURAL_KINDS.includes(kind);
}

export function countryTokens(country) {
  return String(country || "")
    .split(/[／/、（）(),，]/)
    .map((part) => part.trim())
    .filter((part) => part.length >= 2);
}

export function countryPopulationMillions(countryLabel, year) {
  const label = String(countryLabel || "");
  const tokens = countryTokens(label);
  const hits = [];
  for (const token of tokens) {
    if (COUNTRY_POP_MILLIONS[token]) {
      hits.push(interpolateSeries(COUNTRY_POP_MILLIONS[token], year));
    }
  }
  if (!hits.length) {
    for (const [key, series] of Object.entries(COUNTRY_POP_MILLIONS)) {
      if (label.includes(key)) hits.push(interpolateSeries(series, year));
    }
  }
  if (!hits.length) return 0;
  return Math.min(...hits);
}
